private val qrcKey1 = "!@#)(NHLiuy*$%^&".encodeToByteArray()
private val qrcKey2 = "123ZXC!@#)(*$%^&".encodeToByteArray()
private val qrcKey3 = "!@#)(*$%^&abcDEF".encodeToByteArray()
private val offsetTag = "[offset:".encodeToByteArray()

internal fun decodeQqQrcHex(hex: String): String? {
    val encrypted = hex.hexToByteArrayOrNull() ?: return null
    val source = if (encrypted.size >= 2 && encrypted[0].toUByte().toInt() == 0x98 && encrypted[1].toUByte().toInt() == 0x25) {
        encrypted.convertNewQrc()
    } else {
        encrypted
    }
    val offset = if (source.startsWith(offsetTag)) 0x0b else 0
    val content = source.padToDesBlock(offset)
    qrcDes(content, qrcKey1, QqDesType.Decode)
    qrcDes(content, qrcKey2, QqDesType.Encode)
    qrcDes(content, qrcKey3, QqDesType.Decode)
    return inflateQqQrcPayload(content)?.decodeToString()
}

internal expect fun inflateQqQrcPayload(payload: ByteArray): ByteArray?

private enum class QqDesType {
    Encode,
    Decode,
}

private data class QqDesBlock(
    var low: Int,
    var high: Int,
)

private fun qrcDes(src: ByteArray, key: ByteArray, type: QqDesType) {
    QqDesState.makeFirstKey(key)
    var index = 0
    while (index + 7 < src.size) {
        val data = QqDesBlock(
            low = src.readIntLe(index),
            high = src.readIntLe(index + 4),
        )
        QqDesState.handleData(type, data)
        src.writeIntLe(index, data.low)
        src.writeIntLe(index + 4, data.high)
        index += 8
    }
}

private object QqDesState {
    private val subKeys = Array(16) { QqDesBlock(0, 0) }
    private val tempKey = QqDesBlock(0, 0)

    fun makeFirstKey(key: ByteArray) {
        val first = QqDesBlock(
            low = key.readIntLe(0),
            high = key.readIntLe(4),
        )
        tempKey.low = 0
        tempKey.high = 0
        subKeys.forEach { sub ->
            sub.low = 0
            sub.high = 0
        }

        for (index in 0 until 28) {
            var item = desTransform[index]
            var got = if (item <= 32) first.low else first.high
            if ((got and desBitmap[item - 1]) != 0) {
                tempKey.low = tempKey.low or desBitmap[index]
            }

            item = desTransform[index + 28]
            got = if (item <= 32) first.low else first.high
            if ((got and desBitmap[item - 1]) != 0) {
                tempKey.high = tempKey.high or desBitmap[index]
            }
        }

        for (index in 0 until 16) {
            createSubKey(index)
        }
    }

    fun handleData(type: QqDesType, data: QqDesBlock) {
        var low = 0
        var high = 0
        for (index in 0 until 64) {
            val value = desInitial[index]
            val mask = if (value <= 32) {
                desBitmap[value - 1] and data.low
            } else {
                desBitmap[value - 1] and data.high
            }
            if (mask != 0) {
                if (index >= 32) {
                    high = high or desBitmap[index]
                } else {
                    low = low or desBitmap[index]
                }
            }
        }
        data.low = low
        data.high = high

        when (type) {
            QqDesType.Encode -> for (index in 0 until 16) makeData(data, subKeys[index])
            QqDesType.Decode -> for (index in 15 downTo 0) makeData(data, subKeys[index])
        }

        val oldLow = data.low
        data.low = data.high
        data.high = oldLow

        low = 0
        high = 0
        for (index in 0 until 64) {
            val value = desFinal[index]
            val mask = if (value <= 32) {
                desBitmap[value - 1] and data.low
            } else {
                desBitmap[value - 1] and data.high
            }
            if (mask != 0) {
                if (index >= 32) {
                    high = high or desBitmap[index]
                } else {
                    low = low or desBitmap[index]
                }
            }
        }
        data.low = low
        data.high = high
    }

    private fun createSubKey(index: Int) {
        val sub = subKeys[index]
        val rotation = desRotations[index]
        var lowBits = tempKey.low and desRotationMask[rotation]
        var highBits = tempKey.high and desRotationMask[rotation]
        if (rotation == 1) {
            lowBits = lowBits ushr 27
            highBits = highBits ushr 27
        } else {
            lowBits = lowBits ushr 26
            highBits = highBits ushr 26
        }
        tempKey.low = tempKey.low shl rotation
        tempKey.high = tempKey.high shl rotation
        tempKey.low = tempKey.low or (lowBits and 0xFFFFFFF0.toInt())
        tempKey.high = tempKey.high or (highBits and 0xFFFFFFF0.toInt())

        for (bit in 0 until 48) {
            val value = desPermuted[bit]
            if (bit >= 24) {
                if ((desBitmap[value - 28] and tempKey.high) != 0) {
                    sub.high = sub.high or desBitmap[bit - 24]
                }
            } else if ((tempKey.low and desBitmap[value - 1]) != 0) {
                sub.low = sub.low or desBitmap[bit]
            }
        }
    }

    private fun makeData(data: QqDesBlock, subKey: QqDesBlock) {
        var low = 0
        var high = 0
        val tempHigh = data.high
        for (index in 0 until 48) {
            val mask = desBitmap[desExpansion[index] - 1]
            if (index >= 24) {
                if ((mask and tempHigh) != 0) {
                    high = high or desBitmap[index - 24]
                }
            } else if ((mask and tempHigh) != 0) {
                low = low or desBitmap[index]
            }
        }
        low = low xor subKey.low
        high = high xor subKey.high

        val buffer = intArrayOf(
            (low ushr 26) and 0x3f,
            (low ushr 20) and 0x3f,
            (low ushr 14) and 0x3f,
            (low ushr 8) and 0x3f,
            (high ushr 26) and 0x3f,
            (high ushr 20) and 0x3f,
            (high ushr 14) and 0x3f,
            (high ushr 8) and 0x3f,
        )

        data.high = 0
        var byteIndex = 0
        var sboxBase = 0
        while (sboxBase < 448) {
            data.high = (data.high or desSBox[buffer[byteIndex] + sboxBase]) * 16
            byteIndex++
            sboxBase += 64
        }
        data.high = data.high or desSBox[64 * byteIndex + buffer[byteIndex]]

        var tmp = 0
        for (index in 0 until 32) {
            if ((data.high and desBitmap[desPBox[index] - 1]) != 0) {
                tmp = tmp or desBitmap[index]
            }
        }
        data.high = tmp xor data.low
        data.low = tempHigh
    }
}

private fun ByteArray.padToDesBlock(offset: Int): ByteArray {
    var length = size - offset
    val mod = length % 8
    if (mod != 0) length += 8 - mod
    val result = ByteArray(length)
    copyInto(result, destinationOffset = 0, startIndex = offset, endIndex = size)
    return result
}

private fun ByteArray.startsWith(prefix: ByteArray): Boolean =
    size >= prefix.size && prefix.indices.all { index -> this[index] == prefix[index] }

private fun ByteArray.convertNewQrc(): ByteArray =
    ByteArray(size) { index ->
        (this[index].toInt() xor versionConvertCode[(index * index + 0x013c1b) % 256]).toByte()
    }

private fun String.hexToByteArrayOrNull(): ByteArray? {
    val clean = trim()
    if (clean.length % 2 != 0) return null
    return ByteArray(clean.length / 2) { index ->
        val high = clean[index * 2].digitToIntOrNull(16) ?: return null
        val low = clean[index * 2 + 1].digitToIntOrNull(16) ?: return null
        ((high shl 4) or low).toByte()
    }
}

private fun ByteArray.readIntLe(offset: Int): Int =
    (this[offset].toInt() and 0xff) or
        ((this[offset + 1].toInt() and 0xff) shl 8) or
        ((this[offset + 2].toInt() and 0xff) shl 16) or
        ((this[offset + 3].toInt() and 0xff) shl 24)

private fun ByteArray.writeIntLe(offset: Int, value: Int) {
    this[offset] = (value and 0xff).toByte()
    this[offset + 1] = ((value ushr 8) and 0xff).toByte()
    this[offset + 2] = ((value ushr 16) and 0xff).toByte()
    this[offset + 3] = ((value ushr 24) and 0xff).toByte()
}

